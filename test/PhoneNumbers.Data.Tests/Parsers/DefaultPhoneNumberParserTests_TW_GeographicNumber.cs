namespace PhoneNumbers.Tests.Parsers;

/// <summary>
/// Contains unit tests for the <see cref="DefaultPhoneNumberParser"/> class for Taiwan <see cref="PhoneNumber"/>s.
/// </summary>
public class DefaultPhoneNumberParserTests_TW_GeographicNumber
